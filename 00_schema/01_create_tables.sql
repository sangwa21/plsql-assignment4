CREATE TABLE STUDENTS (
    STUDENT_ID NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    FIRST_NAME VARCHAR2(50) NOT NULL,
    LAST_NAME VARCHAR2(50) NOT NULL,
    EMAIL VARCHAR2(100) UNIQUE,
    DATE_OF_BIRTH DATE,
    ENROLLMENT_DATE DATE DEFAULT SYSDATE
);
SELECT * FROM STUDENTS;
CREATE TABLE COURSES (
    COURSE_ID NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    COURSE_CODE VARCHAR2(20) NOT NULL UNIQUE,
    COURSE_NAME VARCHAR2(100) NOT NULL,
    CREDIT_HOURS NUMBER(2) NOT NULL
);
SELECT * FROM COURSES;
CREATE TABLE REGISTRATIONS (
    REGISTRATION_ID NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    STUDENT_ID NUMBER NOT NULL,
    COURSE_ID NUMBER NOT NULL,
    REGISTRATION_DATE DATE DEFAULT SYSDATE,

    CONSTRAINT FK_REG_STUDENT
        FOREIGN KEY (STUDENT_ID)
        REFERENCES STUDENTS(STUDENT_ID),

    CONSTRAINT FK_REG_COURSE
        FOREIGN KEY (COURSE_ID)
        REFERENCES COURSES(COURSE_ID),

    CONSTRAINT UQ_STUDENT_COURSE
        UNIQUE (STUDENT_ID, COURSE_ID)
);
SELECT * FROM REGISTRATIONS;
CREATE TABLE GRADES (
    GRADE_ID NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    REGISTRATION_ID NUMBER NOT NULL,
    SCORE NUMBER(5,2) NOT NULL,
    GRADE_DATE DATE DEFAULT SYSDATE,

    CONSTRAINT FK_GRADE_REGISTRATION
        FOREIGN KEY (REGISTRATION_ID)
        REFERENCES REGISTRATIONS(REGISTRATION_ID),

    CONSTRAINT CHK_GRADE_SCORE
        CHECK (SCORE BETWEEN 0 AND 100),

    CONSTRAINT UQ_REGISTRATION_GRADE
        UNIQUE (REGISTRATION_ID)
);
SELECT * FROM GRADES;

